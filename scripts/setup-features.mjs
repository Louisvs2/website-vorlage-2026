#!/usr/bin/env node
// Interactive wizard for the optional template features (Buchung, Galerie,
// WhatsApp, Analytics). Run via `npm run setup`. Regenerates
// src/config/features.ts from scratch — never hand-edit that file, rerun
// this script instead.

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import prompts from "prompts";

const outputPath = fileURLToPath(
  new URL("../src/config/features.ts", import.meta.url),
);

function isValidUrl(value) {
  try {
    const url = new URL(value);
    return url.protocol === "http:" || url.protocol === "https:";
  } catch {
    return false;
  }
}

async function main() {
  console.log("\nWebsite-Vorlage — Setup optionaler Features\n");

  const answers = await prompts(
    [
      {
        type: "confirm",
        name: "gallery",
        message: "Galerie-Section (Bilder/Referenzen mit Hover) aktivieren?",
        initial: false,
      },
      {
        type: "confirm",
        name: "bookingEnabled",
        message:
          "Buchungsfeature aktivieren (Link zu einem externen Tool wie Calendly/cal.com)?",
        initial: false,
      },
      {
        type: (_value, values) => (values.bookingEnabled ? "text" : null),
        name: "bookingUrl",
        message: "URL des Buchungstools (z. B. https://cal.com/dein-team):",
        validate: (value) =>
          isValidUrl(value)
            ? true
            : "Bitte eine vollständige http(s)-URL angeben.",
      },
      {
        type: "confirm",
        name: "whatsappEnabled",
        message:
          "WhatsApp-Button aktivieren (schwebend, auf jeder Seite sichtbar)?",
        initial: false,
      },
      {
        type: (_value, values) => (values.whatsappEnabled ? "text" : null),
        name: "whatsappNumber",
        message:
          "WhatsApp-Nummer im internationalen Format, nur Ziffern (z. B. 4989123456):",
        validate: (value) =>
          /^\d{6,15}$/.test(value)
            ? true
            : "Nur Ziffern, ohne '+' oder Leerzeichen, im internationalen Format.",
      },
      {
        type: "confirm",
        name: "analytics",
        message:
          "Vercel Analytics + Speed Insights aktivieren (zeigt dann ein Cookie-Consent-Banner)?",
        initial: false,
      },
    ],
    {
      onCancel: () => {
        console.log(
          "\nAbgebrochen — src/config/features.ts wurde nicht verändert.",
        );
        process.exit(1);
      },
    },
  );

  const config = `// Feature flags for optional template add-ons (Buchung, Galerie, WhatsApp,
// Analytics). Generated by \`npm run setup\` — rerun the wizard to change
// these values instead of hand-editing, so this file and the CLIENT.md
// answers stay in sync.

export interface FeatureConfig {
  /** Renders the reference/portfolio gallery on the homepage and /projekte. */
  gallery: boolean;
  /** Links to an external booking tool (Calendly, cal.com, …). */
  booking: { enabled: boolean; url: string };
  /** Floating WhatsApp contact button, visible on every page. */
  whatsapp: { enabled: boolean; number: string };
  /** Vercel Analytics + Speed Insights, gated behind the cookie consent banner. */
  analytics: boolean;
}

export const features: FeatureConfig = {
  gallery: ${Boolean(answers.gallery)},
  booking: {
    enabled: ${Boolean(answers.bookingEnabled)},
    url: ${JSON.stringify(answers.bookingUrl ?? "")},
  },
  whatsapp: {
    enabled: ${Boolean(answers.whatsappEnabled)},
    number: ${JSON.stringify(answers.whatsappNumber ?? "")},
  },
  analytics: ${Boolean(answers.analytics)},
};
`;

  await writeFile(outputPath, config, "utf8");
  console.log("\n✓ src/config/features.ts aktualisiert.\n");
}

main();
